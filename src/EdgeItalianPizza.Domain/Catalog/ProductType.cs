namespace EdgeItalianPizza.Domain.Catalog;

/// <summary>
/// Тип продукта в каталоге — определяет раздел меню и набор характеристик позиции.
/// </summary>
public enum ProductType : byte
{
    /// <summary>
    /// Пицца — основной продукт с выбором размера, теста и ингредиентов.
    /// </summary>
    Pizza = 1,

    /// <summary>
    /// Напиток — кофе, чай, газировка, соки, лимонады, милкшейки.
    /// </summary>
    Drink = 2,

    /// <summary>
    /// Соус — однопорционный продукт без вариантов размера.
    /// </summary>
    Sauce = 3,

    /// <summary>
    /// Комбо-набор — набор продуктов по выгодной цене со скидкой.
    /// </summary>
    Combo = 4,

    /// <summary>
    /// Мерчандайз — фигурки, игрушки, сувениры и прочий несъедобный мерч.
    /// </summary>
    Merchandise = 5,
}
