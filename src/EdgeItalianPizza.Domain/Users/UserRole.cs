namespace EdgeItalianPizza.Domain.Users;

/// <summary>
/// Роль пользователя — определяет права доступа и набор доступных действий в системе.
/// </summary>
public enum UserRole : byte
{
    /// <summary>
    /// Владелец пиццерии. Управляет каталогом, аналитикой, промо и всеми локациями.
    /// </summary>
    Admin = 1,

    /// <summary>
    /// Клиент — просматривает каталог, делает заказы, оплачивает и отслеживает доставку.
    /// Входит по одноразовому коду из SMS или почты.
    /// </summary>
    Customer = 2,

    /// <summary>
    /// Сотрудник кухни — принимает входящие заказы и меняет их статусы по мере готовности.
    /// </summary>
    Staff = 3,

    /// <summary>
    /// Курьер — доставляет заказы своей локации, обновляет статус доставки.
    /// </summary>
    Courier = 4,
}
